
const mongoose = require("mongoose");

// Defines the structure of each technical interview question.
const technicalQuestionSchema = new mongoose.Schema({

    question: {
        type: String,
        required: [true, "Technical question is required"]
    },

    intention: {
        type: String,
        required: [true, "Intention is required"]
    },

    answer: {
        type: String,
        required: [true, "Answer is required"]
    }

}, {
    _id: false
});

// Defines the structure of each behavioral interview question.
const behavioralQuestionSchema = new mongoose.Schema({

    question: {
        type: String,
        required: [true, "Behavioral question is required"]
    },

    intention: {
        type: String,
        required: [true, "Intention is required"]
    },

    answer: {
        type: String,
        required: [true, "Answer is required"]
    }

}, {
    _id: false
});

// Stores skills that the candidate needs to improve, along with their severity.
const skillGapSchema = new mongoose.Schema({

    skill: {
        type: String,
        required: [true, "Skill is required"]
    },

    severity: {
        type: String,
        enum: ["low", "medium", "high"],
        required: [true, "Severity is required"]
    }

}, {
    _id: false
});

// Represents one day in the AI-generated preparation roadmap.
const preparationDaySchema = new mongoose.Schema({

    day: {
        type: Number,
        required: [true, "Day is required"],
        min: 1,
        max: 30
    },

    focus: {
        type: String,
        required: [true, "Focus is required"]
    },

    tasks: {
        type: [String],
        required: [true, "Preparation tasks are required"],

        validate: {
            validator: function (tasks) {
                return tasks.length > 0;
            },
            message: "Each preparation day must contain at least one task"
        }
    }

}, {
    _id: false
});

// Stores the complete adaptive preparation roadmap generated by Gemini.
const preparationPlanSchema = new mongoose.Schema({

    totalDays: {
        type: Number,
        required: [true, "Total preparation days are required"],
        min: 5,
        max: 30
    },

    difficulty: {
        type: String,
        enum: ["beginner", "intermediate", "advanced"],
        required: [true, "Preparation difficulty is required"]
    },

    dailyCommitmentHours: {
        type: Number,
        required: [true, "Daily commitment hours are required"],
        min: 1,
        max: 12
    },

    days: {
        type: [preparationDaySchema],
        required: [true, "Preparation days are required"],

        validate: [
            {
                validator: function (days) {
                    return days.length >= 5 && days.length <= 30;
                },
                message: "Preparation roadmap must contain between 5 and 30 days"
            },

            {
                validator: function (days) {
                    return days.length === this.totalDays;
                },
                message: "Total preparation days must match the number of roadmap entries"
            },

            {
                validator: function (days) {
                    return days.every(
                        (day, index) => day.day === index + 1
                    );
                },
                message: "Preparation day numbers must be sequential, starting from 1"
            }
        ]
    }

}, {
    _id: false
});

// Stores all information associated with an individual interview report.
const interviewReportSchema = new mongoose.Schema({

    // Associates the interview report with the user who generated it.
    user: {
        type: mongoose.Schema.Types.ObjectId,
        ref: "User",
        required: [true, "User reference is required"]
    },

    // Stores the job title identified from the supplied job description.
    jobTitle: {
        type: String,
        required: [true, "Job title is required"],
        trim: true
    },

    // Stores the original job description provided by the candidate.
    jobDescription: {
        type: String,
        required: [true, "Job description is required"]
    },

    // Stores the extracted text from the uploaded resume PDF.
    resume: {
        type: String
    },

    // Stores the candidate's additional self-description.
    selfDescription: {
        type: String
    },

    // Represents how closely the candidate's profile matches the target role.
    matchScore: {
        type: Number,
        min: 0,
        max: 100
    },

    // Stores exactly 10 technical questions with their intentions and answers.
    technicalQuestions: {
        type: [technicalQuestionSchema],

        validate: {
            validator: function (questions) {
                return questions.length === 10;
            },
            message: "Exactly 10 technical questions are required"
        }
    },

    // Stores exactly 5 behavioral questions with their intentions and answers.
    behavioralQuestions: {
        type: [behavioralQuestionSchema],

        validate: {
            validator: function (questions) {
                return questions.length === 5;
            },
            message: "Exactly 5 behavioral questions are required"
        }
    },

    // Stores the candidate's identified skill gaps and their severity.
    skillGaps: {
        type: [skillGapSchema]
    },

    // Stores the personalized preparation roadmap generated by Gemini.
    preparationPlan: {
        type: preparationPlanSchema,
        required: [true, "Preparation roadmap is required"]
    }

}, {
    timestamps: true
});

// Creates the Mongoose model used to create, retrieve and manage interview reports.
const interviewReportModel = mongoose.model(
    "InterviewReport",
    interviewReportSchema
);

module.exports = interviewReportModel;
